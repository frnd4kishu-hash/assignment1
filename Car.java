import java.awt.*;

public abstract class Car {
    //Fields
    public Color color;
    public int nrDoors; // Number of doors on the car


    //Methods
    public Color getColor() {
        return color;
    }

    public void setColor(Color clr) {
        color = clr;
    }

    public int getNrDoors() {
        return nrDoors;
    }




}

